let lang = 'fr';
try {
  const saved = localStorage.getItem('bramblekin.lang');
  if (saved === 'fr' || saved === 'en') lang = saved;
  else if (!navigator.language?.toLowerCase().startsWith('fr')) lang = 'en';
} catch { /* stockage indisponible */ }

export const getLang = () => lang;
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'fr';
  try { localStorage.setItem('bramblekin.lang', lang); } catch { /* ignoré */ }
  document.documentElement.lang = lang;
}

export function t(key, params = {}) {
  const raw = DICT[lang][key] ?? DICT.fr[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

export const has = (key) => key in DICT[lang];

/** Nom localisé d'un objet {fr, en}. */
export const pick = (names) => (names && typeof names === 'object' ? (names[lang] ?? names.fr) : String(names ?? ''));

/** Applique les traductions aux éléments [data-i18n] et [data-i18n-ph]. */
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}

